import { useCallback, useState } from "react";

/**
 * Высота, реально доставшаяся содержимому карточки.
 *
 * Плитка дашборда не тянется под содержимое: её геометрию задаёт буква, а не
 * то, что внутри. Значит «сколько показать» — вопрос не ширины полотна, а
 * этой самой высоты, и медиазапрос о ней ничего не знает: та же плитка
 * оказывается короче при более длинном заголовке, другом масштабе страницы
 * или другом составе строк. Правило, угадывающее по ширине, ошибается на
 * первом же непредусмотренном сочетании — и обрезает строку пополам.
 *
 * Измеряем в момент привязки узла и дальше наблюдателем. React вызывает
 * ref-функцию до кадра, поэтому человек не видит, как список сначала
 * появился целиком, а потом укоротился.
 *
 * `null` значит «ещё не измерено». Нулевая высота — это оно же, а не ответ
 * «не помещается ничего»: так выглядит и первый кадр, и скрытая вкладка, и
 * jsdom, где размеров нет вовсе. Принять ноль за измерение — значит опустошить
 * карточку там, где на самом деле есть место. Вызывающая сторона обязана
 * держать на этот случай свой разумный состав, а не показывать пустоту.
 */
export function useAvailableHeight<T extends HTMLElement>(): [
  (node: T | null) => void | (() => void),
  number | null,
] {
  const [height, setHeight] = useState<number | null>(null);

  const ref = useCallback((node: T | null) => {
    if (!node) return;
    const measure = () =>
      setHeight((previous) => {
        const next = node.clientHeight > 0 ? node.clientHeight : null;
        return previous === next ? previous : next;
      });
    measure();
    if (typeof ResizeObserver === "undefined") return;
    // Наблюдаем именно этот узел: его высоту задаёт плитка, а не содержимое,
    // поэтому пересчёт состава не меняет размер и цикла не возникает.
    const observer = new ResizeObserver(measure);
    observer.observe(node);
    return () => observer.disconnect();
  }, []);

  return [ref, height];
}
