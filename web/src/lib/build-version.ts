/**
 * Узнать, что вкладка работает на устаревшей сборке панели.
 *
 * Зачем это вообще: открытая вкладка владельца живёт сутками и остаётся на
 * бандле, загруженном при первом входе. 27.08 это стоило целой выкатки —
 * презентация первого входа была собрана, проверена и раскатана, а до клиента
 * не дошла: по журналу его браузер ни разу не запросил чанк новой страницы,
 * потому что страница не перезагружалась.
 *
 * Механика простая и не требует новых маршрутов: сервер вшивает идентификатор
 * сборки в HTML (вкладка запоминает его на момент загрузки) и отдаёт его же в
 * `/api/status`, который панель и так опрашивает. Значения разошлись — значит
 * сервер обновился после того, как вкладку открыли.
 */

declare global {
  interface Window {
    /** Сборка, вшитая в этот HTML при отдаче страницы. */
    __KORRA_BUILD__?: string;
  }
}

/** Сборка, с которой стартовала эта вкладка. Пустая строка — сигнала нет. */
export function loadedBuild(): string {
  if (typeof window === "undefined") return "";
  return (window.__KORRA_BUILD__ ?? "").trim();
}

/**
 * Показывать ли предложение обновиться.
 *
 * Fail-quiet по обеим сторонам: пустое значение означает «сигнала нет», а не
 * «сборки разные». Иначе установка не из образа (git/pip, где файла сборки
 * нет) показывала бы владельцу вечное предложение обновиться, которое ничего
 * не чинит.
 */
export function isStaleBuild(
  loaded: string | null | undefined,
  live: string | null | undefined,
): boolean {
  const before = (loaded ?? "").trim();
  const now = (live ?? "").trim();
  if (!before || !now) return false;
  return before !== now;
}
