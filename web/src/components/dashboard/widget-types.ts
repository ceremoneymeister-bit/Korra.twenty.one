import type { ComponentType } from "react";

import type { WidgetSize } from "@/lib/dashboard-layout";
import type { DashboardState } from "@/lib/dashboard-state";

export interface DashboardWidgetBodyProps {
  /**
   * Размер плитки: S 1×1, M 2×1, L 2×2.
   *
   * `undefined` — закреплённая полоса над сеткой: она растёт под содержимое,
   * и сокращать там нечего.
   */
  size?: WidgetSize;
}

/**
 * Переход карточки — один и тот же на любом размере.
 *
 * Живёт в шапке карточки, а не в её содержимом: так он не соревнуется за
 * высоту со строками и не пропадает первым на тесной плитке. `short` — то,
 * что видно рядом с заголовком, `label` — то, что произносит скринридер.
 */
export interface DashboardWidgetAction {
  label: string;
  short: string;
  to: string;
}

/**
 * Встроенный виджет дашборда.
 *
 * Каталог собирается из таких описаний, поэтому страница не знает ни одной
 * карточки по имени: добавить виджет — значит положить файл рядом и вписать
 * его в каталог. Компонент приходит из сборки, а не загружается во время
 * работы: сторонний JavaScript дашборд не исполняет.
 */
export interface DashboardWidget {
  /** Устойчивый идентификатор: по нему хранится раскладка. Он переживает
   *  переименование карточки — `recent-results` называется «Артефакты». */
  id: string;
  /** Название карточки — одно и то же в сетке и в каталоге настройки. */
  title: string;
  /** Одно предложение о том, что карточка показывает человеку. */
  purpose: string;
  /** Карточка живёт полосой над сеткой: без размера и без перестановки. */
  pinned?: boolean;
  /** Куда уйти за полной картиной. Только существующие экраны. */
  action?: DashboardWidgetAction;
  /**
   * Есть ли этой карточке место на этой установке. Нет — карточки нет ни на
   * доске, ни в каталоге (квота Codex без подписки). Сохранённое место и
   * размер при этом не теряются: вернётся источник — вернётся и карточка.
   * Без функции карточка доступна всегда.
   */
  isAvailable?: (state: DashboardState | null) => boolean;
  /** Содержимое карточки: у каждого виджета своё и живёт в его файле. */
  Body: ComponentType<DashboardWidgetBodyProps>;
}
